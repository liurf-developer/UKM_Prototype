function buildTemplateNodes(sections: string[], prefix: string): TemplateNode[] {
  return sections.map((sec, idx) => ({
    id: `${prefix}-node-${idx + 1}`,
    title: sec,
    parentId: null,
    level: 1,
    order: idx + 1,
    defaultValue: '',
    placeholder: `Please enter details for ${sec}...`,
    required: idx === 0,
    enabled: true,
    children: [],
  }));
}

